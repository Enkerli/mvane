/* mvane yard's families of Clipper's sounds, by how each behaves (Alex, 2026-11-22): a chord held 2.5 s (a mono sound:
 * one note), its level over the last half second against its peak: sustained if within 15 dB; Clipper's own kind
 * (gen/clp_kind.h) decides where it is clear (PAD, ORGAN hold; PLUCK, STAB are short; FX). Then
 *   CHORDS  polyphonic, sustained (pads, strings, organs, keys that hold): for chords
 *   HITS    polyphonic, short (plucks, bells, stabs): stabs, hits, bursts, arpeggios
 *   LEADS   mono, sustained (leads, basses): for a wind controller
 *   OTHER   mono and short, and what Clipper files as FX (percussion, noises)
 * written to app/clipper/gen/clp_bank.h ([engine][preset]); clp.c orders the list by family, the LIGHT sounds first
 * in CHORDS and HITS, then Clipper's kind (gen/clp_kind.h). Prints each sound and a count.
 *   make clp-bank */
#include "clp.h"
#include <math.h>
#include <stdio.h>
#include <string.h>
int plat_cpu2_on(void) { return 0; }
int plat_cpu2_run(void (*f)(uint32_t), uint32_t a) { (void)f, (void)a; return 0; }
int plat_cpu2_wait(void) { return 0; }

enum { F_CHORDS, F_HITS, F_LEADS, F_OTHER };
static const char *const FN[4] = {"CHORDS", "HITS", "LEADS", "OTHER"};
uint32_t clp_sound_kind_id(uint32_t i);
static int32_t lr[512];
static uint8_t fam[64][40];

static int list(const char *path)             /* the list as the firmware orders it, by family: docs/SOUNDS.md */
{
    static const char *const COST[3] = {"light", "mid", "heavy"};
    unsigned s, n = clp_sounds(), f = 99;
    FILE *o = fopen(path, "w");
    if (!o)
        return 1;
    fprintf(o, "# Clipper's sounds in mvane yard, by family\n\nGenerated by `make clp-bank` (tools/clp_bank.c): the order "
               "PRESETS runs through, after mvane yard's saw (YARD). A fast turn of PRESETS, or SELECT on the play pages, "
               "goes to the next family. Families by how each sound behaves (held 2.5 s: does it sustain?) and Clipper's "
               "own kind where it is clear; LIGHT: the sounds whose measured CPU is LIGHT (tools/clp_cost.c), first in CHORDS and HITS.\n");
    for (s = 0; s < n; s++) {
        if (clp_sound_family(s) != f) {
            f = clp_sound_family(s);
            fprintf(o, "\n## %s\n\n| Sound | Engine | Kind | Cost |\n| --- | --- | --- | --- |\n", clp_family_name(f));
        }
        fprintf(o, "| %s | %s | %s | %s%s |\n", clp_sound_name(s), clp_sound_engine(s), clp_sound_kind(s),
                COST[clp_sound_cost(s) % 3u], clp_sound_mono(s) ? ", mono" : "");
    }
    fclose(o);
    printf("%s: %u sounds by family\n", path, n);
    return 0;
}

int main(int argc, char **argv)
{
    unsigned s, n, b, i, c, cnt[4][3] = {{0}};
    FILE *f;
    clp_init();
    if (argc > 2 && !strcmp(argv[2], "list"))
        return list(argv[1]);
    clp_bank_on(0);                              /* (as Clipper lists them: the families are what is measured) */
    n = clp_sounds();
    for (s = 0; s < n; s++) {
        static const uint8_t CH[4] = {48, 55, 64, 71};
        unsigned mono = (unsigned)clp_sound_mono(s), nn = mono ? 1u : 4u, k = clp_sound_key(s), fm;
        double peak = 0, held = -1, w;
        clp_panic();
        clp_select(s);
        for (b = 0; b < 60; b++)
            clp_render(lr, 256, 4096);
        for (c = 0; c < nn; c++)
            clp_event(0x91u + c, mono ? 60u : CH[c], 100);
        for (b = 0; b < 430; b++) {              /* 2.5 s held, in windows of 8 blocks (46 ms) */
            static double acc;
            clp_render(lr, 256, 4096);
            for (i = 0; i < 256; i++)
                acc += (double)lr[2 * i] * lr[2 * i];
            if (b % 8u == 7u) {
                w = sqrt(acc / (8.0 * 256));
                acc = 0;
                if (w > peak)
                    peak = w;
                if (b >= 344u && (held < 0 || w < held))   /* the last half second: its quietest window */
                    held = w;
            }
        }
        for (c = 0; c < nn; c++)
            clp_event(0x81u + c, mono ? 60u : CH[c], 0);
        for (b = 0; b < 120; b++)
            clp_render(lr, 256, 4096);
        {
            int sus = peak > 0 && held >= peak * 0.178;   /* -15 dB */
            unsigned kd = clp_sound_kind_id(s);  /* Clipper's kind where it says (pads and organs hold, plucks and
                                                  * stabs are short: a pluck's filter closes while its level holds),
                                                  * the measurement elsewhere (keys, leads, basses, the unfiled) */
            if (kd == 7u)
                fm = F_OTHER;
            else if (mono)
                fm = kd == 5u || kd == 6u ? F_OTHER : kd == 3u || kd == 2u ? F_LEADS : sus ? F_LEADS : F_OTHER;
            else
                fm = (kd == 3u || kd == 2u) && held > peak * 0.01 ? F_CHORDS   /* (one silent by then, -40 dB: a hit) */
                     : kd == 5u || kd == 6u ? F_HITS : sus ? F_CHORDS : F_HITS;
            printf("%-14s %-8s %-5s %s  held %5.1f dB  cost %u  -> %s\n", clp_sound_name(s), clp_sound_engine(s),
                   clp_sound_kind(s), mono ? "mono" : "poly", peak > 0 && held > 0 ? 20 * log10(held / peak) : -99.0,
                   clp_sound_cost(s), FN[fm]);
        }
        if ((k >> 8) < 64u && (k & 0xFFu) < 40u)
            fam[k >> 8][k & 0xFFu] = (uint8_t)fm;
        cnt[fm][clp_sound_cost(s) % 3u]++;
    }
    f = fopen(argc > 1 ? argv[1] : "app/clipper/gen/clp_bank.h", "w");
    if (!f)
        return 1;
    fprintf(f, "/* generated by tools/clp_bank.c (make clp-bank): each factory sound's family, [engine][preset]: 0 CHORDS "
               "(poly, sustained)\n * 1 HITS (poly, short) 2 LEADS (mono, sustained) 3 OTHER (mono and short; FX) */\n"
               "static const uint8_t CLP_FAM[NENGINES][40] = {\n");
    for (b = 0; b < 23u; b++) {
        fprintf(f, "    {");
        for (i = 0; i < 40u; i++)
            fprintf(f, "%u%s", fam[b][i], i < 39u ? "," : "");
        fprintf(f, "},\n");
    }
    fprintf(f, "};\n");
    fclose(f);
    printf("clp_bank: %u sounds\n", n);
    for (i = 0; i < 4u; i++)
        printf("  %-6s %3u  (light %u, mid %u, heavy %u)\n", FN[i], cnt[i][0] + cnt[i][1] + cnt[i][2], cnt[i][0],
               cnt[i][1], cnt[i][2]);
    return 0;
}
