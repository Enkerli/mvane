"""Clipper's own filing of its factory sounds by kind (its firmware/src/ui.c BANK[]: BASS KEYS ORGN PAD LEAD PLCK STAB
FX, by engine and name) into app/clipper/gen/clp_kind.h, which clp.c uses to order the sounds within mvane yard's
families. Usage: tools/gen_clp_kind.py CLIPPER/firmware/src [out.h]"""
import re
import sys

src = sys.argv[1].rstrip('/')
out = sys.argv[2] if len(sys.argv) > 2 else 'app/clipper/gen/clp_kind.h'
engi = {m[0]: int(m[1]) for m in re.findall(r'#define (ENGI_[A-Z0-9]+) (\d+)u', open(f'{src}/core.h').read())}
ui = open(f'{src}/ui.c').read()
start = ui.index('BANK[] = {')
body = ui[start:ui.index('\n};', start)]
rows = []
for kind, e, name in re.findall(r'\{?(BK_[A-Z]+), *([A-Z_0-9]+), *"([^"]+)"\)?', body):
    rows.append((kind, engi[e] if e in engi else int(e), name))
with open(out, 'w') as f:
    f.write('/* generated by tools/gen_clp_kind.py from Clipper\'s firmware/src/ui.c BANK[] (GPL-3.0): its factory '
            'sounds by kind */\n')
    f.write('enum { CK_BASS, CK_KEYS, CK_ORGAN, CK_PAD, CK_LEAD, CK_PLUCK, CK_STAB, CK_FX, CK_NONE };\n')
    f.write('static const struct { uint8_t kind, e; const char *name; } CLP_KIND[] = {\n')
    for kind, e, name in rows:
        f.write(f'    {{CK_{kind[3:]}, {e}, "{name}"}},\n')
    f.write('};\n')
print(f'{out}: {len(rows)} sounds by kind')
