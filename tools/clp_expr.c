/* How each of Clipper's sounds answers expression: a chord (a mono sound: one note) on MPE member channels, rendered
 * three times from the same start, at rest, with full pressure on its channels, and with slide (CC74) at the top;
 * the same window (0.3 to 1.3 s) of each compared with the one at rest: the level's change and the brightness's (the
 * first difference's energy against the signal's, in dB). A run at rest twice gives the floor (sounds with random
 * parts). Prints a TSV: sound, engine, kind, cost, pressure level, pressure brightness, slide level, slide brightness,
 * floor; then the engines by how many of their sounds pressure leaves unchanged. Measured as the factory made them
 * (clp_expr_on(0)), written to app/clipper/gen/clp_expr.h (the sounds clp.c gives a matrix slot), then measured again
 * with the slots: what still does not answer.
 *   make clp-expr        (build/desktop/clp_expr.tsv, app/clipper/gen/clp_expr.h) */
#include "clp.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
int plat_cpu2_on(void) { return 0; }
int plat_cpu2_run(void (*f)(uint32_t), uint32_t a) { (void)f, (void)a; return 0; }
int plat_cpu2_wait(void) { return 0; }

#define BLK 256
#define SKIP 52            /* 0.3 s */
#define MEAS 172           /* 1 s */
static int32_t lr[2 * BLK];

typedef struct { double e, d; } meas_t;

static meas_t take(unsigned s, int press, int slide)
{
    static const uint8_t CH[4] = {48, 55, 64, 71};
    meas_t m = {0, 0};
    unsigned b, i, c, nn = clp_sound_mono(s) ? 1u : 4u;
    double prev = 0;
    clp_panic();
    clp_select(s);
    for (b = 0; b < 60; b++)               /* the old sound fades, the new one's effects settle */
        clp_render(lr, BLK, 4096);
    for (c = 0; c < nn; c++) {
        clp_event(0xD1u + c, press ? 127u : 0u, 0);
        clp_event(0xB1u + c, 74, slide ? 127u : 64u);
        clp_event(0x91u + c, nn == 1u ? 60u : CH[c], 100);
    }
    for (b = 0; b < SKIP + MEAS; b++) {
        clp_render(lr, BLK, 4096);
        if (b < SKIP)
            continue;
        for (i = 0; i < BLK; i++) {
            double x = (double)lr[2 * i] + (double)lr[2 * i + 1];
            m.e += x * x;
            m.d += (x - prev) * (x - prev);
            prev = x;
        }
    }
    for (c = 0; c < nn; c++)
        clp_event(0x81u + c, nn == 1u ? 60u : CH[c], 0);
    for (b = 0; b < 80; b++)
        clp_render(lr, BLK, 4096);
    return m;
}

static double db(double a, double b) { return a > 0 && b > 0 ? 10.0 * log10(a / b) : 0.0; }

static unsigned flag[64][40];

static unsigned pass(FILE *f, unsigned *deaf, unsigned *cnt, const char **ename, unsigned *sdeaf)
{
    unsigned s, n = clp_sounds(), e, total = 0;
    for (s = 0; s < n; s++) {
        meas_t r0 = take(s, 0, 0), r1 = take(s, 0, 0), p = take(s, 1, 0), sl = take(s, 0, 1);
        double fl = fabs(db(r1.e, r0.e)) + fabs(db(r1.d / (r1.e + 1), r0.d / (r0.e + 1)));
        double pl = db(p.e, r0.e), pb = db(p.d / (p.e + 1), r0.d / (r0.e + 1));
        double ql = db(sl.e, r0.e), qb = db(sl.d / (sl.e + 1), r0.d / (r0.e + 1));
        int pd = fabs(pl) < 1.0 + fl && fabs(pb) < 1.0 + fl, sd = fabs(ql) < 1.0 + fl && fabs(qb) < 1.0 + fl;
        unsigned k = clp_sound_key(s);
        e = k >> 8;
        if (e < 64u) {
            cnt[e]++, deaf[e] += (unsigned)pd, sdeaf[e] += (unsigned)sd, ename[e] = clp_sound_engine(s);
            if ((k & 0xFFu) < 40u)
                flag[e][k & 0xFFu] = (unsigned)pd | (unsigned)sd << 1;
        }
        total += (unsigned)pd;
        if (f)
            fprintf(f, "%s\t%s\t%s\t%u\t%.1f\t%.1f\t%.1f\t%.1f\t%.1f\n", clp_sound_name(s), clp_sound_engine(s),
                    clp_sound_kind(s), clp_sound_cost(s), pl, pb, ql, qb, fl);
    }
    return total;
}

int main(int argc, char **argv)
{
    unsigned e, p, deaf[64] = {0}, cnt[64] = {0}, sdeaf[64] = {0}, d2[64] = {0}, c2[64] = {0}, s2[64] = {0}, t0, t1;
    const char *ename[64] = {0};
    FILE *f;
    clp_init();
    f = fopen(argc > 1 ? argv[1] : "build/desktop/clp_expr.tsv", "w");
    if (!f)
        return 1;
    fprintf(f, "sound\tengine\tkind\tcost\tpress_level_db\tpress_bright_db\tslide_level_db\tslide_bright_db\tfloor_db\n");
    clp_expr_on(0);
    t0 = pass(f, deaf, cnt, ename, sdeaf);
    fclose(f);
    f = fopen(argc > 2 ? argv[2] : "app/clipper/gen/clp_expr.h", "w");
    if (!f)
        return 1;
    fprintf(f, "/* generated by tools/clp_expr.c (make clp-expr): the factory sounds full pressure (1) or slide (2) leaves\n"
               " * unchanged, [engine][preset]: clp.c gives them a matrix slot */\n"
               "static const uint8_t CLP_EXPR[NENGINES][40] = {\n");
    for (e = 0; e < 23u; e++) {
        fprintf(f, "    {");
        for (p = 0; p < 40u; p++)
            fprintf(f, "%u%s", flag[e][p], p < 39u ? "," : "");
        fprintf(f, "},\n");
    }
    fprintf(f, "};\n");
    fclose(f);
    printf("clp_expr: %u sounds; as the factory made them, %u unchanged by full pressure (within 1 dB of level and "
           "brightness)\n", clp_sounds(), t0);
    if (argc > 3) {                              /* (the second pass needs clp.c built with the table just written) */
        clp_expr_on(1);
        t1 = pass(0, d2, c2, ename, s2);
        printf("with the matrix slots: %u unchanged by pressure\n", t1);
        for (e = 0; e < 64u; e++)
            if (cnt[e])
                printf("  %-8s pressure %2u -> %2u, slide %2u -> %2u unchanged, of %2u\n", ename[e], deaf[e], d2[e],
                       sdeaf[e], s2[e], cnt[e]);
    }
    return 0;
}
