/* Each Clipper sound's trim (clp.c, fx.c CLP_TRIM): played hard (reduction(): velocity 127, full pressure, chords of
 * six in quick succession; a mono sound, notes) at MASTER all the way up (as USB AUDIO FULL records it); the master
 * limiter's deepest gain reduction (fx.c lim_dac) gives the trim that keeps it under, less 1 dB, never above 1. Writes app/clipper/gen/clp_trim.h, then plays every sound again with its trim: what limiting is left.
 *   make clp-trim */
#include <math.h>
#include <stdio.h>
#include <string.h>
#include "clp.c"
int plat_cpu2_on(void) { return 0; }
int plat_cpu2_run(void (*f)(uint32_t), uint32_t a) { (void)f, (void)a; return 0; }
int plat_cpu2_wait(void) { return 0; }
static int32_t lr[512];

/* dB the limiter took off, at its deepest, played hard (0.10): velocity 127 and full pressure on every note (the
 * FM-1's keys send it all the time; the expression slots raise some sounds' level with it), chords of six struck
 * every quarter second over a held bass, eight of them; a mono sound, eight notes */
static double reduction(unsigned s)
{
    static const uint8_t CH[4][5] = {{52, 55, 59, 64, 67}, {57, 60, 64, 67, 72}, {53, 57, 60, 62, 65}, {55, 59, 62, 65, 67}};
    unsigned b, c, k, r, mono = (unsigned)clp_sound_mono(s);
    int32_t gmin = 32768;
    clp_panic();
    clp_select(s);
    for (b = 0; b < 40; b++)
        clp_render(lr, 256, 4096);
    for (c = 0; c < 6u; c++)
        clp_event(0xD1u + c, 127, 0);
    if (mono)
        for (r = 0; r < 8u; r++) {
            clp_event(0x91, 60u + (r % 4u) * 3u, 127);
            for (b = 0; b < 40; b++) {
                clp_render(lr, 256, 4096);
                gmin = lim_dac.g < gmin ? lim_dac.g : gmin;
            }
            clp_event(0x81, 60u + (r % 4u) * 3u, 0);
        }
    else {
        clp_event(0x91, 36, 127);
        for (r = 0; r < 8u; r++) {
            k = r % 4u;
            for (c = 0; c < 5u; c++)
                clp_event(0x92u + c, CH[k][c], 127);
            for (b = 0; b < 43; b++) {
                clp_render(lr, 256, 4096);
                gmin = lim_dac.g < gmin ? lim_dac.g : gmin;
            }
            for (c = 0; c < 5u; c++)
                clp_event(0x82u + c, CH[k][c], 0);
        }
        clp_event(0x81, 36, 0);
    }
    for (c = 0; c < 6u; c++)
        clp_event(0xD1u + c, 0, 0);
    for (b = 0; b < 150; b++)
        clp_render(lr, 256, 4096);
    return -20.0 * log10((double)gmin / 32768.0);
}

int main(int argc, char **argv)
{
    static uint16_t q[64][40];
    unsigned s, n, e, p, trimmed = 0, left3 = 0, left1 = 0;
    double worst = 0, before[512];
    FILE *f;
    clp_init();
    clp_trim_on(0);
    n = clp_sounds();
    for (s = 0; s < n && s < 512u; s++) {
        unsigned k = clp_sound_key(s);
        double r = before[s] = reduction(s), g = r > 0.5 ? pow(10.0, -(r + 1.0) / 20.0) : 1.0;
        if ((k >> 8) < 64u && (k & 0xFFu) < 40u)
            q[k >> 8][k & 0xFFu] = (uint16_t)(g < 1.0 ? g * 32768.0 : 0);
        trimmed += g < 1.0;
    }
    f = fopen(argc > 1 ? argv[1] : "app/clipper/gen/clp_trim.h", "w");
    if (!f)
        return 1;
    fprintf(f, "/* generated by tools/clp_trim.c (make clp-trim): each factory sound's trim, Q15, [engine][preset]: a chord "
               "of six\n * (a mono sound: a note) under the master limiter; 0 none */\nstatic const uint16_t "
               "CLP_TRIM_Q15[NENGINES][40] = {\n");
    for (e = 0; e < 23u; e++) {
        fprintf(f, "    {");
        for (p = 0; p < 40u; p++)
            fprintf(f, "%u%s", q[e][p], p < 39u ? "," : "");
        fprintf(f, "},\n");
    }
    fprintf(f, "};\n");
    fclose(f);
    printf("clp_trim: %u sounds, %u trimmed\n", n, trimmed);
    if (argc > 2) {                              /* (built again with the table: what is left) */
        clp_trim_on(1);
        for (s = 0; s < n && s < 512u; s++) {
            double r = reduction(s);
            left1 += r > 1.0, left3 += r > 3.0;
            if (r > worst)
                worst = r;
            if (r > 3.0)
                printf("  %-14s %-8s %.1f dB still (%.1f before)\n", clp_sound_name(s), clp_sound_engine(s), r, before[s]);
        }
        printf("with the trims: %u sounds limited over 1 dB, %u over 3 dB; the deepest %.1f dB\n", left1, left3, worst);
    }
    return 0;
}
