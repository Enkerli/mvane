/* Each of Clipper's sounds measured on this computer as the FM-1 plays it (0.10): a chord of six (mvane yard's bass
 * and five voices; a mono sound, a note), its trim and expression slots in place, the second core's half of the
 * voices timed apart (a job run while this core waits, as the FM-1 runs it alongside): the block's cost on the FM-1
 * is about the longer of the two halves. Then app/clipper/gen/clp_cost.h, a tier for each: 0 EZ, 1 HRD (over
 * CLP_EZ_US, about 40% of the FM-1 with such a chord: Alex's readings, 2026-11-22, fit at 1.25% a microsecond here
 * plus 22%). Prints each sound's figures, and the engines ranked.
 *   make clp-cost */
#include <stdio.h>
#include <string.h>
#include <time.h>
#include "clp.c"
#define CLP_EZ_US 15.0
static void (*job)(uint32_t);
static uint32_t job_arg;
static double job_s;
static double now(void)
{
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return t.tv_sec + t.tv_nsec * 1e-9;
}
int plat_cpu2_on(void) { return 1; }
int plat_cpu2_run(void (*f)(uint32_t), uint32_t a) { job = f, job_arg = a; return 1; }
int plat_cpu2_wait(void)
{
    if (job) {
        double t0 = now();
        job(job_arg);
        job_s += now() - t0;
        job = 0;
    }
    return 0;
}
static int32_t lr[512];
static double us_of[512];

int main(int argc, char **argv)
{
    static const uint8_t CH[6] = {36, 52, 55, 59, 64, 67};
    unsigned s, n, e, r, ez = 0;
    double eng_sum[64] = {0};
    unsigned eng_n[64] = {0};
    const char *eng_name[64] = {0};
    FILE *f;
    clp_init();
    clp_cores(2);
    n = clp_sounds();
    for (s = 0; s < n && s < 512u; s++) {
        int mono = clp_sound_mono(s);
        unsigned nn = mono ? 1u : 6u, b, c;
        double best = 1e9, bj = 0;
        for (r = 0; r < 3u; r++) {               /* (the quickest of three: the machine's noise out) */
            double t0, T, J;
            clp_panic();
            clp_select(s);
            for (b = 0; b < 40; b++)
                clp_render(lr, 256, 4096);
            for (c = 0; c < nn; c++)
                clp_event(0x91u + c, mono ? 60u : CH[c], 100);
            for (b = 0; b < 20; b++)
                clp_render(lr, 256, 4096);
            job_s = 0;
            t0 = now();
            for (b = 0; b < 200; b++)
                clp_render(lr, 256, 4096);
            T = (now() - t0) / 200 * 1e6, J = job_s / 200 * 1e6;
            for (c = 0; c < nn; c++)
                clp_event(0x81u + c, mono ? 60u : CH[c], 0);
            for (b = 0; b < 100; b++)
                clp_render(lr, 256, 4096);
            if (T < best)
                best = T, bj = J;
        }
        us_of[s] = best - bj > bj ? best - bj : bj;
        ez += us_of[s] <= CLP_EZ_US;
        e = clp_sound_key(s) >> 8;
        eng_sum[e] += us_of[s], eng_n[e]++, eng_name[e] = clp_sound_engine(s);
        printf("%-14s %-8s %s %5.1f us (second core %4.1f) -> %s\n", clp_sound_name(s), clp_sound_engine(s),
               mono ? "mono" : "poly", us_of[s], bj, us_of[s] <= CLP_EZ_US ? "EZ" : "HRD");
    }
    f = fopen(argc > 1 ? argv[1] : "app/clipper/gen/clp_cost.h", "w");
    if (!f)
        return 1;
    fprintf(f, "/* generated by tools/clp_cost.c (make clp-cost): each sound's cost on the FM-1's two cores, a chord of six, "
               "[engine][preset]:\n * 0 EZ (a block's longer half %.0f us or less here), 1 HRD */\n"
               "static const uint8_t CLP_COST[NENGINES][40] = {\n", CLP_EZ_US);
    {
        static uint8_t t[64][40];
        for (s = 0; s < n; s++) {
            unsigned k = clp_sound_key(s);
            if ((k >> 8) < 64u && (k & 0xFFu) < 40u)
                t[k >> 8][k & 0xFFu] = (uint8_t)(us_of[s] > CLP_EZ_US);
        }
        for (e = 0; e < 23u; e++) {
            unsigned p;
            fprintf(f, "    {");
            for (p = 0; p < 40u; p++)
                fprintf(f, "%u%s", t[e][p], p < 39u ? "," : "");
            fprintf(f, "},\n");
        }
    }
    fprintf(f, "};\n");
    fclose(f);
    printf("clp_cost: %u sounds, %u EZ (%.0f us or less), %u HRD; engines, lightest first:\n", n, ez, CLP_EZ_US, n - ez);
    for (;;) {                                   /* (a selection sort for the printout) */
        double m = 1e18;
        unsigned best_e = 0;
        int found = 0;
        for (e = 0; e < 64u; e++)
            if (eng_n[e] && eng_sum[e] / eng_n[e] < m)
                m = eng_sum[e] / eng_n[e], best_e = e, found = 1;
        if (!found)
            break;
        printf("  %-8s %5.1f us (%u sounds)\n", eng_name[best_e], m, eng_n[best_e]);
        eng_n[best_e] = 0;
    }
    return 0;
}
