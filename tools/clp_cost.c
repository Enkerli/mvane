/* Each of Clipper's sounds measured on this computer (one core, the effect buses as loaded): a four-note chord (a
 * mono sound plays one), its render time over two seconds; then app/clipper/gen/clp_cost.h, a tier for each:
 * 0 LIGHT, 1 MID, 2 HEAVY (the thirds of the range above the idle chain). The FM-1 is much slower, the ranking holds.
 *   make clp-cost        (prints the engines ranked too) */
#include "clp.h"
#include <stdio.h>
#include <stdlib.h>
#include <time.h>
int plat_cpu2_on(void) { return 0; }
int plat_cpu2_run(void (*f)(uint32_t), uint32_t a) { (void)f, (void)a; return 0; }
int plat_cpu2_wait(void) { return 0; }
static int32_t lr[512];
static double us[512];
int main(int argc, char **argv)
{
    unsigned s, n, e, best_e = 0;
    double lo = 1e9, hi = 0, eng_sum[64] = {0};
    unsigned eng_n[64] = {0};
    const char *eng_name[64] = {0};
    FILE *f;
    clp_init();
    n = clp_sounds();
    for (s = 0; s < n && s < 512u; s++) {
        clock_t a;
        int b, best = 0;
        clp_select(s);
        for (b = 0; b < 30; b++)
            clp_render(lr, 256, 4096);
        clp_event(0x91, 48, 100), clp_event(0x92, 55, 100), clp_event(0x93, 64, 100), clp_event(0x94, 71, 100);
        for (b = 0; b < 10; b++)
            clp_render(lr, 256, 4096);
        a = clock();
        for (b = 0; b < 344; b++)
            clp_render(lr, 256, 4096);
        us[s] = 1e6 * (double)(clock() - a) / CLOCKS_PER_SEC / 344;
        (void)best;
        if (us[s] < lo) lo = us[s];
        if (us[s] > hi) hi = us[s];
        e = clp_sound_key(s) >> 8;
        eng_sum[e] += us[s], eng_n[e]++, eng_name[e] = clp_sound_engine(s);
        clp_panic();
        for (b = 0; b < 40; b++)
            clp_render(lr, 256, 4096);
    }
    f = fopen(argc > 1 ? argv[1] : "app/clipper/gen/clp_cost.h", "w");
    if (!f)
        return 1;
    fprintf(f, "/* generated by tools/clp_cost.c (make clp-cost): each sound's cost tier, [engine][preset], 0 LIGHT 1 MID 2 HEAVY */\n");
    fprintf(f, "static const uint8_t CLP_COST[NENGINES][40] = {\n");
    {
        static uint8_t t[64][40];
        for (s = 0; s < n; s++) {
            unsigned k = clp_sound_key(s), tier = us[s] < lo + (hi - lo) / 5.0 ? 0u : us[s] < lo + (hi - lo) * 0.45 ? 1u : 2u;
            if ((k >> 8) < 64u && (k & 0xFFu) < 40u)
                t[k >> 8][k & 0xFFu] = (uint8_t)tier;
        }
        for (e = 0; e < 23u; e++) {
            unsigned p;
            fprintf(f, "    {");
            for (p = 0; p < 40u; p++)
                fprintf(f, "%u%s", t[e][p], p < 39u ? "," : "");
            fprintf(f, "},\n");
        }
    }
    fprintf(f, "};\n");
    fclose(f);
    printf("clp_cost: %u sounds, %.1f .. %.1f us a block here; engines, lightest first:\n", n, lo, hi);
    for (;;) {                                   /* (a selection sort for the printout) */
        double m = 1e18;
        int found = 0;
        for (e = 0; e < 64u; e++)
            if (eng_n[e] && eng_sum[e] / eng_n[e] < m)
                m = eng_sum[e] / eng_n[e], best_e = e, found = 1;
        if (!found)
            break;
        printf("  %-8s %5.1f us (%u sounds)\n", eng_name[best_e], m, eng_n[best_e]);
        eng_n[best_e] = 0;
    }
    return 0;
}
